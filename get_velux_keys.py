def _norm(s: str) -> str:
    """Normalise a field name for keyword matching."""
    return s.lower().replace("_", "").replace(".", "").replace("-", "")


def _search_keys(obj: Any, prefix: str = "") -> dict:
    """Recursively search a JSON object for key-related fields."""
    found: dict = {}
    keywords = {"key", "sign", "hash", "secret", "security", "token"}
    if isinstance(obj, dict):
        for k, v in obj.items():
            full = f"{prefix}.{k}" if prefix else k
            if any(kw in _norm(k) for kw in keywords):
                found[full] = v
            found.update(_search_keys(v, full))
    elif isinstance(obj, list):
        for i, item in enumerate(obj):
            found.update(_search_keys(item, f"{prefix}[{i}]"))
    return found


def _to_b64_padded(value: str) -> str | None:
    """Return a properly padded base64 string from hex or base64 input."""
    try:
        raw = bytes.fromhex(value)
        return base64.b64encode(raw).decode()
    except Exception:
        pass
    padded = value + "=" * (-len(value) % 4)
    try:
        base64.b64decode(padded)
        return padded
    except Exception:
        pass
    return None


