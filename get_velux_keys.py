#!/usr/bin/env python3
"""
VELUX Active — Key Extraction Tool
====================================
Retrieves the HashSignKey (sign_key) and SignKeyId (sign_key_id) needed
to open windows via the VELUX Active Home Assistant integration.

OVERVIEW
--------
VELUX windows require two cryptographic keys to accept open/close commands
from Home Assistant. These keys are generated by your VELUX gateway and stored
inside the VELUX Active app on your iPhone. This script extracts them so you
can enter them into the Home Assistant integration settings.

═══════════════════════════════════════════════════════════════════
STEP-BY-STEP GUIDE
═══════════════════════════════════════════════════════════════════

STEP 1 — Install Python dependencies
─────────────────────────────────────
Open a terminal (Command Prompt / PowerShell on Windows, Terminal on Mac)
and run:

    pip install requests pycryptodome iphone-backup-decrypt

STEP 2 — Create an encrypted iPhone backup  ← IMPORTANT
──────────────────────────────────────────────────────────
The VELUX keys are stored in your iPhone's keychain. They can only be
extracted from an *encrypted* backup (unencrypted backups do not include
the keychain).

  On Windows (Apple Devices):
    1. Install "Apple Devices" from the Microsoft Store if you haven't already.
    2. Open Apple Devices and connect your iPhone via USB.
    3. Click your iPhone in the left sidebar.
    4. Under "Backups", select "Back up all of the data on your iPhone
       to this Windows PC".
    5. Tick "Encrypt local backup" and set a password you will remember.
    6. Click "Back Up Now" and wait for it to finish.

  On Mac (Finder):
    1. Connect your iPhone via USB and open Finder.
    2. Select your iPhone in the sidebar.
    3. Under "Backups", select "Back up all of the data on your iPhone
       to this Mac".
    4. Tick "Encrypt local backup" and set a password.
    5. Click "Back Up Now" and wait for it to finish.

  ⚠  Make sure the VELUX Active app is installed and has successfully
     paired with your gateway BEFORE making the backup. The keys are
     only written to the keychain after a successful pairing.

STEP 3 — Run this script
─────────────────────────
In the same terminal, navigate to the folder containing this file and run:

    python get_velux_keys.py

The script will:
  • Ask for your VELUX Active email and password
  • Try to retrieve keys directly from the VELUX API (fast, sometimes works)
  • If that fails, locate your iPhone backup automatically and ask for
    the backup encryption password you set in Step 2
  • Decrypt the backup keychain and search for the VELUX keys
  • Print the two values you need to copy into Home Assistant

STEP 4 — Enter the keys into Home Assistant
────────────────────────────────────────────
  1. Open Home Assistant and go to:
       Settings → Devices & Services → VELUX Active → Configure
  2. Paste the HashSignKey value into the "sign_key" field.
  3. Paste the SignKeyId value into the "sign_key_id" field.
  4. Click Submit. Home Assistant will reload the integration.
  5. Test by pressing Open on one of your VELUX windows.

═══════════════════════════════════════════════════════════════════

TROUBLESHOOTING
───────────────
• "Backup is NOT encrypted" — repeat Step 2 and tick "Encrypt local backup".
• "Wrong passphrase" — try the password you set when creating the backup.
  Note: this is separate from your Apple ID password.
• "No VELUX keys found" — ensure the backup was made AFTER the VELUX app
  paired with the gateway. Delete the old backup, re-pair the app if needed,
  then make a fresh encrypted backup.
• Keys found but windows still don't open — double-check you copied the full
  values without extra spaces, and reload the integration after saving.

If you're still stuck, open an issue at:
  https://github.com/GMounsor/velux/issues
"""

